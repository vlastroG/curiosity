import { complete } from './api.js';

/** Значения температуры по умолчанию, которые пользователь может отредактировать в UI. */
export const DEFAULT_TEMPERATURES = [0, 0.7, 1.2];

/**
 * Требования к оформлению ответа. Без этого модель на высокой температуре с той же
 * вероятностью съезжает в LaTeX или широкие markdown-таблицы, которые не влезают
 * в узкую колонку.
 */
const FORMAT_SYSTEM = [
  'Отвечай на русском языке в простом Markdown.',
  'Разрешены: заголовки уровня ### и ниже, маркированные и нумерованные списки,',
  '**жирный**, *курсив*, `моноширинный` и блоки кода в тройных апострофах.',
  'Формулы и вычисления записывай обычным текстом в одну строку',
  '(например: t = S / v = 1500 / 20 = 75 с).',
  'Категорически не используй LaTeX: ни \\( \\), ни \\[ \\], ни \\frac, ни \\text, ни \\cdot.',
  'Не используй таблицы -- ответ показывается в узкой колонке.',
].join(' ');

/**
 * Один вызов с заданной температурой. Никаких многошаговых цепочек -- сравнение всегда
 * "один и тот же запрос, один вызов, разная температура".
 */
export async function runAt(temperature, { messages }) {
  const result = await complete({ messages, system: FORMAT_SYSTEM, temperature });
  return {
    text: result.text,
    usage: result.usage,
    calls: 1,
    finishReason: result.finishReason,
    latencyMs: result.latencyMs,
  };
}
