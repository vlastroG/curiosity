// Расшифровка погоды и её смысл для стройки.
//
// Два разных перевода одного и того же. Первый -- технический: код WMO в слова,
// иначе в ответе поедет голое число 61, которое ничего не значит ни человеку,
// ни модели. Второй -- доменный: те же цифры, но с точки зрения того, можно ли
// сегодня работать на улице. Второй перевод и есть причина, по которой сервер
// отдаёт текст, а не только числа: 16 градусов и 90% влажности -- это факт,
// а «цементная стяжка будет сохнуть дольше обычного» -- уже вывод, и делать его
// лучше там, где известны единицы измерения.

import (
	"fmt"
	"strings"
)

