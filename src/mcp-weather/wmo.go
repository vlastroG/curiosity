// weatherText -- код WMO словами.
//
// Неизвестный код не проглатывается: провайдер вправе добавить новый, и увидеть
// «код 88» в ответе честнее, чем увидеть пустую строку и гадать, что случилось.
func weatherText(code int) string {
	if text, ok := weatherCodes[code]; ok {
		return text
	}
	return fmt.Sprintf("код погоды %d", code)
}

// Пороги, за которыми наружные работы перестают быть обычными.
//
// Числа не из головы: +5 °C -- граница, ниже которой цементные смеси набирают
// прочность заметно медленнее, а большинство красок и грунтовок просто нельзя
// наносить; 0 °C -- вода в растворе замерзает; +30 °C и прямое солнце сушат
// поверхность быстрее, чем она успевает схватиться; влажность выше 85% растягивает
// сушку; ветер от 30 км/ч мешает работать на высоте и уносит распыляемое.
const (
	coldLimit     = 5.0
	freezingLimit = 0.0
	heatLimit     = 30.0
	humidLimit    = 85
	windLimit     = 30.0
)

// wetCodes -- коды, при которых с неба что-то идёт.
func wet(code int) bool {
	return code >= 51 && code != 77
}

// workHint -- что нынешние условия значат для наружных работ.
//
// Возвращает строку для человека и для модели: перечень того, что сегодня мешает,
// либо прямое «условия для наружных работ обычные». Пустой строки не бывает --
// молчание здесь читалось бы как «данных нет», а не как «всё хорошо».
func workHint(c Conditions) string {
	var notes []string

	switch {
	case c.Temperature < freezingLimit:
		notes = append(notes, "мороз: мокрые процессы без противоморозных добавок и обогрева не ведут")
	case c.Temperature < coldLimit:
		notes = append(notes, "холодно: цементные смеси набирают прочность медленнее, "+
			"большинство красок и грунтовок наносить нельзя")
	case c.Temperature > heatLimit:
		notes = append(notes, "жарко: поверхность сохнет быстрее, чем схватывается, нужен уход за свежим слоем")
	}

	if c.Precipitation > 0 || wet(c.Code) {
		notes = append(notes, "идут осадки: наружные мокрые работы и окраску откладывают")
	}
	if c.Humidity > humidLimit {
		notes = append(notes, fmt.Sprintf("высокая влажность (%d%%): сушка затянется", c.Humidity))
	}
	if c.WindSpeed > windLimit {
		notes = append(notes, fmt.Sprintf("сильный ветер (%.0f км/ч): работы на высоте и распыление небезопасны", c.WindSpeed))
	}

	if len(notes) == 0 {
		return "условия для наружных работ обычные"
	}
	return strings.Join(notes, "; ")
}
