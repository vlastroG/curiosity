// Готовые профили.
//
// Та же логика, что у заготовок знаний: сам профиль приложение за пользователя
// не сочиняет, но перед пустой формой «опишите свои предпочтения» человек обычно
// не знает, что туда писать. Заготовка показывает жанр: не «будь краток»,
// а конкретные обстоятельства, стиль, формат и ограничения.
//
// Заодно это готовый материал для проверки из задания: один и тот же вопрос
// на двух разных профилях должен давать заметно разные ответы.

